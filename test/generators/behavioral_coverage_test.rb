    # Emitted flows with no behavioral test yet — the debt ledger. Empty: every
    # generated controller flow now has starter behavioral coverage. Add an entry here
    # (rather than leaving a controller unclassified) if a future flow lands
    # before its test does. Each key must match a real, still-uncovered template.
    KNOWN_GAPS = {}.freeze

    # Deliberately not behavior-tested. Keys are path prefixes; each must match at
    # least one template (staleness guard below).
    SKIP = {
      "controllers/concerns/" =>
        "controller concerns (authentication/authorization/captchable/easy_dev_login/sudoable) are " \
        "exercised indirectly by every controller test that runs behind them — sudoable's require_sudo " \
        "guard specifically by users/sudos_controller_test, which drives a really-guarded action",
      "controllers/base_controller.rb.tt" =>
        "a namespaced identity's base controller is wiring; its behavior surfaces " \
        "through that identity's own controller tests",
      "controllers/admin_controller.rb.tt" =>
        "abstract superclass for the Admin::* controllers; the behavior lives in the subclasses",
      "controllers/settings_controller.rb.tt" =>
        "abstract superclass for the Settings::* controllers; the behavior lives in the subclasses",
      "controllers/users/easy_dev_logins_controller.rb.tt" =>
        "development-only 'sign in as anyone' shortcut, not production behavior"
    }.freeze

    def all_controller_templates
      Dir.glob(File.join(TEMPLATES_ROOT, "controllers", "**", "*.tt"))
         .map { |p| p.sub("#{TEMPLATES_ROOT}/", "") }
    end

    # Every controller template lands in exactly one bucket. An unclassified one
    # (a newly added controller nobody triaged) fails here — the regrowth guard.
    def test_every_controller_is_classified
      classified = COVERAGE.keys.to_set | KNOWN_GAPS.keys.to_set

      all_controller_templates.each do |tmpl|
        in_named = classified.include?(tmpl)
        in_skip = SKIP.keys.any? { |prefix| tmpl.start_with?(prefix) }

        assert in_named || in_skip,
               "Controller template is not classified for behavioral coverage:\n  #{tmpl}\n" \
               "Add it to COVERAGE (with a test), KNOWN_GAPS (record the debt), or SKIP (with a reason)."
        refute(in_named && in_skip,
               "Controller template is both named and SKIP-matched — pick one:\n  #{tmpl}")
      end
    end

    # The core guarantee: whenever a build emits a covered controller, it also
    # emits that controller's test. So "generate feature X" always yields "test
    # for feature X" — the coverage can't silently detach. Enforced for every
    # identity in every scenario (namespaced ones included — each renders on its own,
    # a valid single-identity build) by rendering each invocation alone.
    def test_covered_controllers_ship_their_test
      Scenarios::ALL.each do |name, invocations|
        invocations.each do |flags|
          built = render_and_record(name, [flags])
          COVERAGE.each do |controller, test|
            next unless built.include?(controller)

            assert_includes built, test,
                            "#{name.inspect} (#{flags.join(" ")}) builds #{controller} but not #{test}. " \
                            "Wire the test into AuthnzElevenGenerator#create_tests under the controller's predicate."
          end
        end
      end
    end

    # A COVERAGE test template must exist on disk (a typo'd path would otherwise
    # make the co-emission check above silently vacuous for un-built scenarios).
    def test_coverage_test_templates_exist
      missing = COVERAGE.values.reject { |t| File.exist?(File.join(TEMPLATES_ROOT, t)) }
      assert_empty missing, "COVERAGE maps to test templates that don't exist:\n  #{missing.join("\n  ")}"
    end

    # KNOWN_GAPS keys must be real, currently-uncovered controllers — so the ledger
    # can't carry a stale entry (renamed away) or one already moved into COVERAGE.
    def test_known_gaps_are_real_and_uncovered
      stale = KNOWN_GAPS.keys.reject { |k| File.exist?(File.join(TEMPLATES_ROOT, k)) }
      assert_empty stale, "KNOWN_GAPS names templates that don't exist (remove them):\n  #{stale.join("\n  ")}"

      moved = KNOWN_GAPS.keys & COVERAGE.keys
      assert_empty moved,
                   "In both KNOWN_GAPS and COVERAGE — drop the stale gap entry:\n  #{moved.join("\n  ")}"
    end

    # Every SKIP prefix must still match a template — a dead prefix (renamed dir)
    # is misleading. Mirrors ScenarioCompletenessTest's staleness guard.
    def test_skip_prefixes_are_live
      dead = SKIP.keys.reject { |prefix| all_controller_templates.any? { |t| t.start_with?(prefix) } }
      assert_empty dead, "These SKIP prefixes match no controller template (remove them):\n  #{dead.join("\n  ")}"
    end

    private

    def render_and_record(name, invocations)
      recorded = []
      Dir.mktmpdir("coverage_#{name}") do |dir|
        SKELETON.each do |entry|
          src = File.join(DUMMY_APP_ROOT, entry)
          FileUtils.cp_r(src, File.join(dir, entry)) if File.exist?(src)
        end
        recorder = recorder_module(recorded)
        invocations.each do |flags|
          gen = AuthnzElevenGenerator.new([], flags)
          gen.destination_root = dir
          gen.singleton_class.prepend(recorder)
          silence { gen.invoke_all }
        end
      end
      recorded.select { |s| s.end_with?(".tt") }.to_set
    end

    def recorder_module(sink)
      Module.new do
        define_method(:template) do |source, *rest, &blk|
          sink << source.to_s
          super(source, *rest, &blk)
        end
        define_method(:migration_template) do |source, *rest, &blk|
          sink << source.to_s
          super(source, *rest, &blk)
        end
        define_method(:copy_file) do |source, *rest, &blk|
          sink << source.to_s
          super(source, *rest, &blk)
        end
        define_method(:run) { |*_args, **_opts| nil }
      end
    end

    def silence
      original = $stdout
      $stdout = File.open(File::NULL, "w")
      yield
    ensure
      $stdout.close
      $stdout = original
    end
  end
