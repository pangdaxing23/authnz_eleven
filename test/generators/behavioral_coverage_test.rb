module AuthnzEleven
  # Sibling to ScenarioCompletenessTest:
  # that one guarantees every *template* is built by some scenario; this one
  # guarantees every emitted *controller flow* has a behavioral test built
  # alongside it — the net that catches "a user edits a generated controller,
  # breaks it, and the generated suite stays green because nothing tested it."
  #
  # Every controller template on disk must be classified exactly once as:
  #   COVERAGE   — a behavioral test template exercises it, and (asserted below)
  #                every scenario that builds the controller also builds that test.
  #   KNOWN_GAPS — a flow we intend to cover but haven't yet. The living to-do
  #                list; the goal is to burn it down to empty. Listed here so the
  #                gap is *visible*, not silent.
  #   SKIP       — deliberately not behavior-tested, with a reason (infra exercised
  #                indirectly, dev-only shortcuts, WebAuthn ceremonies that need a
  #                virtual authenticator).
  #
  # A newly added controller that fits none of the three fails the test: you must
  # write a test (COVERAGE), record the debt (KNOWN_GAPS), or justify the skip
  # (SKIP). That's what stops the behavioral gap from silently regrowing.
